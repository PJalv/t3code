import * as Schema from "effect/Schema";
import { PositiveInt } from "./baseSchemas.ts";
import {
  GerritAccount,
  GerritChangeKey,
  GerritChangeNumber,
  GerritPatchSetNumber,
  GerritReadChange,
  GitCommitOid,
} from "./gerrit.ts";

const Text = Schema.String.check(Schema.isMaxLength(100_000));
const OpaqueId = Schema.String.check(Schema.isNonEmpty(), Schema.isMaxLength(4096));
export const GerritCommentRange = Schema.Struct({
  start_line: PositiveInt,
  start_character: Schema.Int.check(Schema.isGreaterThanOrEqualTo(0)),
  end_line: PositiveInt,
  end_character: Schema.Int.check(Schema.isGreaterThanOrEqualTo(0)),
}).check(
  Schema.makeFilter(
    (r) =>
      r.end_line > r.start_line ||
      (r.end_line === r.start_line && r.end_character >= r.start_character),
  ),
);
export const GerritCommentAnchor = Schema.Struct({
  path: Schema.NullOr(OpaqueId),
  side: Schema.Literals(["REVISION", "PARENT"]),
  parent: Schema.optionalKey(PositiveInt),
  line: Schema.optionalKey(Schema.Int.check(Schema.isGreaterThanOrEqualTo(0))),
  range: Schema.optionalKey(GerritCommentRange),
});
export const GerritComment = Schema.Struct({
  id: OpaqueId,
  patchSet: Schema.NullOr(GerritPatchSetNumber),
  revision: Schema.NullOr(GitCommitOid),
  contentCommit: Schema.optionalKey(Schema.NullOr(GitCommitOid)),
  nativeParent: Schema.optionalKey(Schema.Int),
  identity: Schema.optionalKey(
    Schema.Union([
      Schema.Struct({ kind: Schema.Literal("known") }),
      Schema.Struct({
        kind: Schema.Literals(["unknown", "contradictory"]),
        reason: Schema.String,
      }),
    ]),
  ),
  anchor: GerritCommentAnchor,
  message: Schema.NullOr(Text),
  author: Schema.NullOr(GerritAccount),
  updated: Schema.String,
  inReplyTo: Schema.NullOr(OpaqueId),
  /**
   * The change message this comment was published with. Comments published together share one
   * id, so a watch groups them as one review publish. Absent on drafts and older Gerrit data.
   */
  changeMessageId: Schema.optionalKey(OpaqueId),
  unresolved: Schema.NullOr(Schema.Boolean),
  visibility: Schema.Literals(["published", "server-draft"]),
});
export type GerritComment = typeof GerritComment.Type;
export const GerritPortedComment = Schema.Struct({
  id: OpaqueId,
  original: Schema.NullOr(GerritComment),
  displayAnchor: GerritCommentAnchor,
  displayRevision: GitCommitOid,
});
export const GerritActionInfo = Schema.Struct({
  method: Schema.optionalKey(Schema.String),
  label: Schema.optionalKey(Schema.String),
  title: Schema.optionalKey(Schema.String),
  enabled: Schema.optionalKey(Schema.Boolean),
});
export const GerritApproval = Schema.Struct({
  ...GerritAccount.fields,
  value: Schema.optionalKey(Schema.Int),
  date: Schema.optionalKey(Schema.String),
});
export const GerritLabel = Schema.Struct({
  values: Schema.optionalKey(Schema.Record(Schema.String, Schema.String)),
  all: Schema.optionalKey(Schema.Array(GerritApproval)),
  approved: Schema.optionalKey(GerritAccount),
  rejected: Schema.optionalKey(GerritAccount),
  optional: Schema.optionalKey(Schema.Boolean),
});
export const GerritRequirement = Schema.Struct({
  name: Schema.String,
  description: Schema.optionalKey(Schema.String),
  status: Schema.String,
  source: Schema.optionalKey(Schema.Literal("legacy-submit-rule")),
});
export const GerritChangeMessage = Schema.Struct({
  id: OpaqueId,
  author: Schema.optionalKey(GerritAccount),
  date: Schema.String,
  message: Text,
  _revision_number: Schema.optionalKey(GerritPatchSetNumber),
  /**
   * Gerrit's own classification of the entry, for example `autogenerated:gerrit:newPatchSet` or
   * `autogenerated:gerrit:review`. Present only on autogenerated messages; a person's comment has
   * no tag, so the timeline must fall back to the message text.
   */
  tag: Schema.optionalKey(Schema.String),
});
export const GerritCheck = Schema.Struct({
  repository: Schema.String,
  change_number: GerritChangeNumber,
  patch_set_id: GerritPatchSetNumber,
  checker_uuid: OpaqueId,
  state: Schema.Literals([
    "NOT_STARTED",
    "SCHEDULED",
    "RUNNING",
    "SUCCESSFUL",
    "FAILED",
    "NOT_RELEVANT",
  ]),
  checker_name: Schema.optionalKey(Schema.String),
  checker_status: Schema.optionalKey(Schema.Literals(["ENABLED", "DISABLED"])),
  checker_description: Schema.optionalKey(Text),
  started: Schema.optionalKey(Schema.String),
  finished: Schema.optionalKey(Schema.String),
  message: Schema.optionalKey(Text),
  url: Schema.optionalKey(Schema.String),
  created: Schema.String,
  updated: Schema.String,
});
export const GerritReviewDetail = Schema.Struct({
  change: GerritReadChange,
  commitMessage: Schema.NullOr(Text),
  topic: Schema.NullOr(Schema.String),
  updated: Schema.NullOr(Schema.String),
  metaRevision: Schema.NullOr(GitCommitOid),
  reviewers: Schema.Record(Schema.String, Schema.Array(GerritAccount)),
  removableReviewers: Schema.Array(GerritAccount),
  labels: Schema.Record(Schema.String, GerritLabel),
  permittedLabels: Schema.Record(Schema.String, Schema.Array(Schema.Int)),
  actions: Schema.Record(Schema.String, GerritActionInfo),
  revisionActions: Schema.Record(Schema.String, GerritActionInfo),
  requirements: Schema.NullOr(Schema.Array(GerritRequirement)),
  mergeable: Schema.NullOr(Schema.Boolean),
  submittable: Schema.NullOr(Schema.Boolean),
  messages: Schema.Array(GerritChangeMessage),
  messageAccounts: Schema.optionalKey(Schema.Record(Schema.String, GerritAccount)),
  comments: Schema.Array(GerritComment),
  drafts: Schema.Array(GerritComment),
  portedComments: Schema.Array(GerritPortedComment),
  porting: Schema.Literals(["available", "unavailable"]),
  checks: Schema.Union([
    Schema.Struct({
      kind: Schema.Literal("available"),
      values: Schema.Array(GerritCheck),
      profile: Schema.Literal("checks-rest-v1-3.10"),
    }),
    Schema.Struct({ kind: Schema.Literal("not-configured") }),
    Schema.Struct({ kind: Schema.Literal("unavailable"), reason: Schema.String }),
  ]),
  observedAt: Schema.String,
});
export type GerritReviewDetail = typeof GerritReviewDetail.Type;
export const GerritReviewInput = Schema.Struct({
  key: GerritChangeKey,
  number: GerritChangeNumber,
  revision: GitCommitOid,
});
export type GerritReviewInput = typeof GerritReviewInput.Type;

export const GerritReviewerSearchInput = Schema.Struct({
  ...GerritReviewInput.fields,
  query: Schema.String.check(Schema.isNonEmpty(), Schema.isMaxLength(128)),
  state: Schema.Literals(["REVIEWER", "CC"]),
});
export const GerritDiffComparison = Schema.Union([
  Schema.Struct({ kind: Schema.Literal("base") }),
  Schema.Struct({ kind: Schema.Literal("parent"), parent: PositiveInt }),
  Schema.Struct({ kind: Schema.Literal("revision"), revision: GitCommitOid }),
]);
export const GerritFilesInput = Schema.Struct({
  ...GerritReviewInput.fields,
  comparison: GerritDiffComparison,
});
export const GerritDiffInput = Schema.Struct({ ...GerritFilesInput.fields, path: OpaqueId });
export const GerritFile = Schema.Struct({
  path: OpaqueId,
  status: Schema.String,
  oldPath: Schema.NullOr(Schema.String),
  binary: Schema.Boolean,
  inserted: Schema.Int,
  deleted: Schema.Int,
  size: Schema.NullOr(Schema.Number),
});
export const GerritDiffContent = Schema.Struct({
  a: Schema.optionalKey(Schema.Array(Schema.String)),
  b: Schema.optionalKey(Schema.Array(Schema.String)),
  ab: Schema.optionalKey(Schema.Array(Schema.String)),
  skip: Schema.optionalKey(Schema.Int.check(Schema.isGreaterThanOrEqualTo(0))),
});
export const GerritDiffResult = Schema.Union([
  Schema.Struct({
    kind: Schema.Literal("text"),
    header: Schema.Array(Schema.String),
    content: Schema.Array(GerritDiffContent),
    oldPath: Schema.NullOr(Schema.String),
    newPath: Schema.NullOr(Schema.String),
  }),
  Schema.Struct({
    kind: Schema.Literals(["binary", "submodule", "oversize", "unavailable-history"]),
    reason: Schema.String,
  }),
]);
export type GerritDiffResult = typeof GerritDiffResult.Type;

export class GerritWriteError extends Schema.TaggedError<GerritWriteError>()("GerritWriteError", {
  reason: Schema.Literals([
    "authority",
    "invalid-input",
    "stale",
    "expired",
    "not-found",
    "scope-busy",
    "unsupported",
    "persistence",
    "permission",
    "account-changed",
    "chain-blocked",
    "cherry-pick-conflict",
    "rebase-conflict",
  ]),
  /** A bounded, user-facing explanation for a chain precondition. Never a response body. */
  detail: Schema.optionalKey(Schema.String.check(Schema.isMaxLength(2048))),
  /** Set only when the caller proved that no HTTP write request was sent. */
  notDispatched: Schema.optionalKey(Schema.Literal(true)),
}) {
  override get message(): string {
    return this.detail ?? `Gerrit write blocked (${this.reason}).`;
  }
}
